"""Finite checks for the BogomolovPopInjectivity audit (see NOTES.md). Run: python3 -I toy_check.py

Check A: the Lean lemma polynomial_power_prime's dichotomy: (X+1)^n = X^n+1 in k[X]
  iff n = 1 or n = p^r with p = char k. Brute force over F_p (p <= 13) and char 0, n <= 300.
Check B: finite toy of the injectivity mechanism. K = F_q(x), automorphisms in PGammaL2(F_q)
  (constants mapped onto constants, like PerfectIsom). Kummer data restricted to the sum-zero
  subspace V of (Z/ell)^{P^1(F_q)} (= subgroup of K^x/k^x(K^x)^ell generated by x - t).
  Map alpha -> its action on V modulo F_ell^x scalars. Claim: injective.
  Absolute Frobenius f -> f^p acts on V as the scalar p (so it vanishes mod scalars).
Controls: (C1) rank-1 piece span(e_0 - e_inf) collapses distinct maps; (C2) sign of the action
  collapses; (M) mutant instrument that drops the Galois twist must lose injectivity when e > 1.
"""
import itertools, sys
from math import comb

# ---------- Check A ----------
def is_power_of(n, p):
    while n % p == 0: n //= p
    return n == 1
def frob_identity(n, p):   # p = 0 means char 0
    return all((comb(n, i) % p == 0) if p else comb(n, i) == 0 for i in range(1, n))
failA = 0
for p in [0, 2, 3, 5, 7, 11, 13]:
    for n in range(1, 301):
        want = (n == 1) if p == 0 else is_power_of(n, p)
        if frob_identity(n, p) != want: failA += 1; print("A mismatch", p, n)
print(f"Check A (Frobenius dichotomy, p in {{0,2,..,13}}, n<=300): mismatches={failA}")

# ---------- GF(q) ----------
IRRED = {(2,1):[1,1], (3,1):[1,1], (5,1):[1,1], (7,1):[1,1],
         (2,2):[1,1,1], (2,3):[1,1,0,1], (3,2):[1,0,1]}   # low->high coeffs, monic
class GF:
    def __init__(s, p, e):
        s.p, s.e, s.q = p, e, p**e
        s.mod = IRRED[(p, e)]
        s.els = list(itertools.product(range(p), repeat=e))   # tuples, low->high
        s.idx = {x: i for i, x in enumerate(s.els)}
        s.mt = [[s.idx[s._mul(a, b)] for b in s.els] for a in s.els]
        s.zero, s.one = s.idx[(0,)*e], s.idx[(1,)+(0,)*(e-1)]
    def _mul(s, a, b):
        if s.e == 1: return ((a[0]*b[0]) % s.p,)
        r = [0]*(2*s.e-1)
        for i, x in enumerate(a):
            for j, y in enumerate(b): r[i+j] += x*y
        for d in range(len(r)-1, s.e-1, -1):
            c = r[d] % s.p
            if c:
                for k in range(s.e + 1): r[d-s.e+k] -= c*s.mod[k]
        return tuple(v % s.p for v in r[:s.e])
    def add(s, a, b): return s.idx[tuple((x+y) % s.p for x, y in zip(s.els[a], s.els[b]))]
    def neg(s, a): return s.idx[tuple((-x) % s.p for x in s.els[a])]
    def mul(s, a, b): return s.mt[a][b]
    def inv(s, a): return next(b for b in range(s.q) if s.mt[a][b] == s.one)
    def frob(s, a, j):
        r = a
        for _ in range(j):
            x = r; acc = s.one
            for _ in range(s.p): acc = s.mul(acc, x)
            r = acc
        return r

INF = 'inf'
def mobius(F, M, z):
    a, b, c, d = M
    if z == INF: return INF if c == F.zero else F.mul(a, F.inv(c))
    num = F.add(F.mul(a, z), b); den = F.add(F.mul(c, z), d)
    return INF if den == F.zero else F.mul(num, F.inv(den))

def pgl2(F):
    seen, out = set(), []
    for M in itertools.product(range(F.q), repeat=4):
        a, b, c, d = M
        if F.add(F.mul(a, d), F.neg(F.mul(b, c))) == F.zero: continue
        key = tuple(mobius(F, M, z) for z in [*range(F.q), INF])  # PGL2 elt = its point map
        if key in seen: continue
        seen.add(key); out.append(M)
    return out

def inverse_matrix(F, M):
    a, b, c, d = M
    return (d, F.neg(b), F.neg(c), a)       # adjugate = inverse up to scalar

def point_action(F, M, j, galois=True):
    """alpha: c -> c^{p^j}, x -> M(x).  alpha(x - t) vanishes at M^{-1}(tau t): t -> M^{-1}(tau t)."""
    Mi = inverse_matrix(F, M)
    pts = [*range(F.q), INF]
    tw = (lambda t: t if t == INF else F.frob(t, j)) if galois else (lambda t: t)
    return tuple(mobius(F, Mi, tw(t)) for t in pts), pts

def action_on_V(F, perm, pts, ell, scalar=1):
    """Matrix of the permutation on V = sum-zero subspace, basis e_t - e_inf (t finite)."""
    pos = {t: i for i, t in enumerate(pts)}
    n = len(pts) - 1
    cols = []
    for t in pts[:-1]:
        v = [0]*(n+1); v[pos[perm[pos[t]]]] += scalar; v[pos[perm[pos[INF]]]] -= scalar
        cols.append(tuple(v[i] % ell for i in range(n)))  # sum-zero vector = its finite coordinates
    # in basis {e_t - e_inf}, a sum-zero vector v has coordinates v[t] for t finite
    return tuple(cols)

def mod_scalars(Mat, ell):
    return min(tuple(tuple((lam*x) % ell for x in col) for col in Mat) for lam in range(1, ell))

def run(p, e, ell, galois=True, invariant='full'):
    F = GF(p, e); classes = {}; total = 0
    for M in pgl2(F):
        for j in range(e):
            perm, pts = point_action(F, M, j, galois)
            if invariant == 'full':
                key = mod_scalars(action_on_V(F, perm, pts, ell), ell)
            elif invariant == 'rank1':     # only elements preserving {0, inf}; action on e_0 - e_inf
                pos = {t: i for i, t in enumerate(pts)}
                im0, iminf = perm[pos[F.zero]], perm[pos[INF]]
                if {im0, iminf} != {F.zero, INF}: continue
                key = mod_scalars((((1 if im0 == F.zero else ell-1) % ell,),), ell)
            elif invariant == 'sign':
                seen, sgn = set(), 1
                for s in range(len(perm)):
                    if s in seen: continue
                    L, c = 0, s
                    pos = {t: i for i, t in enumerate(pts)}
                    while c not in seen: seen.add(c); c = pos[perm[c]]; L += 1
                    sgn *= (-1)**(L-1)
                key = sgn
            total += 1
            classes.setdefault(key, []).append((M, j))
    coll = [v for v in classes.values() if len(v) > 1]
    return total, len(classes), coll, F

def frob_scalar_check(p, e, ell):
    """Absolute Frobenius f->f^p: (x-t) -> (x-t)^p, i.e. action on V is scalar p. Compose with alpha."""
    F = GF(p, e); bad = 0
    for M in pgl2(F)[:50]:
        perm, pts = point_action(F, M, 0)
        A = action_on_V(F, perm, pts, ell); B = action_on_V(F, perm, pts, ell, scalar=p)
        same_raw = (A == B); same_mod = mod_scalars(A, ell) == mod_scalars(B, ell)
        if not same_mod: bad += 1
    return bad, same_raw

ok = True
for (p, e, ell) in [(2,1,3),(3,1,2),(5,1,2),(5,1,3),(7,1,2),(7,1,3),(2,2,3),(2,2,5),(3,2,2),(2,3,3),(2,3,7)]:
    tot, ncls, coll, F = run(p, e, ell)
    inj = not coll; ok &= inj
    bad, same_raw = frob_scalar_check(p, e, ell)
    print(f"B q={p}^{e} ell={ell}: |PGammaL2|={tot} classes={ncls} injective={inj}; "
          f"Frobenius twist equal mod scalars: {bad==0} (raw matrices equal: {same_raw})")
    ok &= (bad == 0)
# Controls
for (p, e, ell) in [(5,1,3),(7,1,2),(2,2,5)]:
    tot, ncls, coll, F = run(p, e, ell, invariant='rank1')
    ex = coll[0][:2] if coll else None
    print(f"C1 rank-1 control q={p}^{e} ell={ell}: {tot} maps -> {ncls} classes; collision e.g. {ex}")
    ok &= bool(coll)
    tot, ncls, coll, F = run(p, e, ell, invariant='sign')
    print(f"C2 sign control q={p}^{e} ell={ell}: {tot} maps -> {ncls} classes; collision e.g. {coll[0][:2]}")
    ok &= bool(coll)
for (p, e, ell) in [(2,2,3),(3,2,2),(2,3,3)]:
    tot, ncls, coll, F = run(p, e, ell, galois=False)
    print(f"M mutant (drop Galois twist) q={p}^{e} ell={ell}: {tot} maps -> {ncls} classes; "
          f"collision e.g. {coll[0][:2] if coll else None}")
    ok &= bool(coll)
print("ALL EXPECTED:", ok and failA == 0)
sys.exit(0 if ok and failA == 0 else 1)
