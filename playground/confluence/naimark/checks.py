"""Finite-dimensional checks of the DEFINITIONS used by OAI.NaimarkZFC.main.

These are not checks of the theorem (which is about an infinite-dimensional, nonseparable-scale
algebra built by a transfinite recursion). They check, on small examples, that the challenge's
definitions behave as the standard ones do:

  * IsIrreducible  (nonzero, no nontrivial closed invariant subspace) is decided, in finite
    dimension, by the commutant of pi(A) being the scalars (Schur / double commutant).
  * UnitarilyEquivalent (an isometric intertwiner U with U pi(a) = rho(a) U).
  * HasUniqueIrreducibleRepresentation: M_n has exactly one irrep up to equivalence;
    C^2 = C (+) C has two inequivalent ones (NEGATIVE CONTROL: the hypothesis fails).
  * The theorem's other conjuncts on M_n: simple, faithful tracial state, and IS K(C^n),
    so the conjunct "not FiniteDimensional" is what excludes it (second control).

Run: python3 checks.py   (numpy only)
"""
import itertools
import numpy as np

rng = np.random.default_rng(20261008)
TOL = 1e-9


def commutant_dim(ops, d):
    """dim {X in M_d : X T = T X for all T in ops}, via the null space of the linear map X -> [X,T]."""
    rows = []
    for T in ops:
        # vec(XT - TX) = (T^T kron I - I kron T) vec(X)   (column-major vec)
        rows.append(np.kron(T.T, np.eye(d)) - np.kron(np.eye(d), T))
    M = np.vstack(rows)
    s = np.linalg.svd(M, compute_uv=False)
    return int(np.sum(s < TOL * max(1.0, s.max())))


def intertwiner_dim(ops_pi, ops_rho, dpi, drho):
    """dim {U : drho x dpi | U pi(a) = rho(a) U for generators a}."""
    rows = []
    for P, R in zip(ops_pi, ops_rho):
        # vec(U P - R U) = (P^T kron I_drho - I_dpi kron R) vec(U)
        rows.append(np.kron(P.T, np.eye(drho)) - np.kron(np.eye(dpi), R))
    M = np.vstack(rows)
    s = np.linalg.svd(M, compute_uv=False)
    return int(np.sum(s < TOL * max(1.0, s.max())))


def matrix_units(n):
    out = []
    for i, j in itertools.product(range(n), repeat=2):
        E = np.zeros((n, n), complex)
        E[i, j] = 1
        out.append(E)
    return out


def random_unitary(d):
    Z = rng.normal(size=(d, d)) + 1j * rng.normal(size=(d, d))
    Q, R = np.linalg.qr(Z)
    return Q * (np.diag(R) / abs(np.diag(R)))


def check(name, cond):
    print(("PASS " if cond else "FAIL ") + name)
    assert cond, name


print("== M_n: defining representation is irreducible (commutant = scalars)")
for n in (1, 2, 3, 4):
    check(f"M_{n}: commutant dim of identity rep = 1", commutant_dim(matrix_units(n), n) == 1)

print("== M_n: a rotated copy U(.)U* is irreducible AND unitarily equivalent to the defining rep")
for n in (2, 3):
    U = random_unitary(n)
    rho = [U @ E @ U.conj().T for E in matrix_units(n)]
    check(f"M_{n}: rotated rep irreducible", commutant_dim(rho, n) == 1)
    check(f"M_{n}: intertwiner space id->rotated has dim 1", intertwiner_dim(matrix_units(n), rho, n, n) == 1)
    # The intertwiner can be chosen unitary: U itself.
    check(f"M_{n}: U intertwines", all(np.allclose(U @ E, R @ U) for E, R in zip(matrix_units(n), rho)))

print("== M_n: the k-fold amplification a -> I_k (x) a is REDUCIBLE (commutant = M_k, dim k^2)")
for n, k in ((2, 2), (2, 3), (3, 2)):
    amp = [np.kron(np.eye(k), E) for E in matrix_units(n)]
    check(f"M_{n} amplified x{k}: commutant dim = {k*k}", commutant_dim(amp, n * k) == k * k)
    # every irreducible piece is the defining rep: Hom(defining, amplified) has dim k
    check(f"M_{n} amplified x{k}: Hom(defining, amplified) dim = {k}",
          intertwiner_dim(matrix_units(n), amp, n, n * k) == k)

print("== M_n: other conjuncts of `main` hold, and M_n IS K(C^n)")
for n in (2, 3):
    tr = lambda a: np.trace(a) / n
    As = [rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n)) for _ in range(20)]
    check(f"M_{n}: normalized trace is tracial", all(abs(tr(a @ b) - tr(b @ a)) < 1e-9 for a in As for b in As))
    check(f"M_{n}: normalized trace faithful on samples", all(tr(a.conj().T @ a).real > 0 for a in As))
    check(f"M_{n}: tr(1) = 1 (norm 1 state)", abs(tr(np.eye(n)) - 1) < 1e-12)
    # simplicity: the two-sided ideal generated by any nonzero a is everything; E_ij a E_kl spans M_n
    a = As[0]
    span = np.array([(Ei @ a @ Ej).reshape(-1) for Ei in matrix_units(n) for Ej in matrix_units(n)])
    check(f"M_{n}: ideal generated by a random a is all of M_n (rank {n*n})",
          np.linalg.matrix_rank(span, tol=1e-9) == n * n)
    print(f"     M_{n} = B(C^{n}) = K(C^{n}) (every operator on a finite-dim space is compact): "
          "so M_n is NOT a counterexample; only the conjunct `not FiniteDimensional` excludes it.")

print("== NEGATIVE CONTROL: C^2 = C (+) C")
# generators of C^2 as diagonal 1x1-valued characters: e1=(1,0), e2=(0,1)
chi1 = [np.array([[1.0 + 0j]]), np.array([[0.0 + 0j]])]
chi2 = [np.array([[0.0 + 0j]]), np.array([[1.0 + 0j]])]
check("chi1 is irreducible (1-dim, nonzero)", commutant_dim(chi1, 1) == 1 and any(abs(T[0, 0]) > 0 for T in chi1))
check("chi2 is irreducible (1-dim, nonzero)", commutant_dim(chi2, 1) == 1 and any(abs(T[0, 0]) > 0 for T in chi2))
check("Hom(chi1, chi2) = 0: chi1, chi2 NOT unitarily equivalent", intertwiner_dim(chi1, chi2, 1, 1) == 0)
diag = [np.diag([1.0, 0.0]).astype(complex), np.diag([0.0, 1.0]).astype(complex)]
check("defining rep of C^2 on C^2 is REDUCIBLE (commutant dim 2)", commutant_dim(diag, 2) == 2)
check("C^2 is not simple: ideal C(+)0 is proper and nonzero (rank of e1*C^2 = 1 < 2)",
      np.linalg.matrix_rank(np.array([np.diag(diag[0] @ d).real for d in diag])) == 1)
print("     => HasUniqueIrreducibleRepresentation FAILS for C^2, as it must; and C^2 is not simple.")

print("ALL CHECKS PASSED")
