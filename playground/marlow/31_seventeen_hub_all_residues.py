"""Check every base residue and lifts for the K_{17,t} formula.

Run: python3 -I playground/marlow/31_seventeen_hub_all_residues.py
Even bases are generated by item 30's explicit cycle weave.
"""

import json
from pathlib import Path


HUBS = 17
HALF = 8
HERE = Path(__file__).resolve().parent
SEEDS = json.loads((HERE / '31_seventeen_hub_odd_seeds.json').read_text())
assert set(SEEDS) == {'19', '21', '23', '25', '27', '29', '31'}


def offset_cycle(offset, start):
    return {'hubs': [(-i) % HUBS for i in range(HUBS)],
            'leaves': [start + ((-i + offset) % HUBS)
                       for i in range(HUBS)]}


def base_certificate(base):
    assert 16 <= base <= 32
    if base % 2 == 0:
        # Delete hub 16, then weave K_{16,base} into base/2 C_32 cycles.
        m = base//2
        singles = [(HUBS-1, leaf) for leaf in range(base)]
        cycles = [{'hubs': list(range(HUBS-1)),
                   'leaves': [2*((c+j) % m)+q
                              for j in range(HALF) for q in (0, 1)]}
                  for c in range(m)]
        assert len(cycles) == m and all(len(c['hubs']) == 16 for c in cycles)
    elif base == HUBS:
        singles = [(hub, hub) for hub in range(HUBS)]
        cycles = [offset_cycle(offset, 0) for offset in range(1, HUBS, 2)]
    else:
        data = SEEDS[str(base)]
        singles = [tuple(edge) for edge in data['singleton_spokes']]
        cycles = list(data['cycles'])
        j = (base-HUBS)//2
        assert sorted(len(c['hubs']) for c in cycles) == [HUBS-1]*j + [HUBS]*HALF
        degrees = [sum(hub == a for a, _ in singles) for hub in range(HUBS)]
        assert sorted(degrees) == [1]*(HUBS-j) + [3]*j
        missed = [tuple(set(range(HUBS))-set(c['hubs']))
                  for c in cycles if len(c['hubs']) == HUBS-1]
        assert {a for (a,) in missed} == {a for a, d in enumerate(degrees) if d == 3}
    return singles, cycles


def certificate(base, blocks=0):
    assert 16 <= base <= 32 and blocks >= 0
    t = base + HUBS*blocks
    singles, cycles = base_certificate(base)
    for block in range(blocks):
        start = base + HUBS*block
        singles.extend((hub, start+hub) for hub in range(HUBS))
        cycles.extend(offset_cycle(offset, start)
                      for offset in range(1, HUBS, 2))
    seen = set()
    for hub, leaf in singles:
        assert 0 <= hub < HUBS and 0 <= leaf < t
        assert (hub, leaf) not in seen
        seen.add((hub, leaf))
    for cycle in cycles:
        hs, ls = cycle['hubs'], cycle['leaves']
        assert 2 <= len(hs) == len(ls) <= HUBS
        assert len(set(hs)) == len(hs) and len(set(ls)) == len(ls)
        for i, hub in enumerate(hs):
            assert 0 <= hub < HUBS
            for leaf in (ls[i], ls[i-1]):
                assert 0 <= leaf < t and (hub, leaf) not in seen, (t, hub, leaf)
                seen.add((hub, leaf))
    assert seen == {(hub, leaf) for hub in range(HUBS) for leaf in range(t)}
    assert len(singles) == t
    assert len(cycles) == (HALF*t + HUBS-1)//HUBS
    return singles, cycles


def draw(path):
    paper, ink, muted = '#f7f4ed', '#25313a', '#5c6970'
    even, block, witness = '#567aa5', '#3b927e', '#b47751'
    width, gap, x0 = 72, 9, 32
    parts = [f'<rect width="1450" height="420" fill="{paper}"/>',
             f'<text x="32" y="49" font-size="27" fill="{ink}">Seventeen hubs: every base residue has a construction</text>',
             f'<text x="32" y="78" font-size="15" fill="{muted}">t = 16,…,32; each 17-leaf block adds 25 parts</text>']
    for b in range(16, 33):
        x = x0 + (b-16)*(width+gap)
        color, label = ((even, 'weave') if b % 2 == 0 else
                        (block, 'offset') if b == 17 else (witness, 'walk'))
        parts.extend([f'<rect x="{x}" y="124" width="{width}" height="155" rx="8" fill="#fffdf8" stroke="#d7d4ca"/>',
                      f'<rect x="{x}" y="124" width="{width}" height="7" fill="{color}"/>',
                      f'<text x="{x+width/2}" y="165" text-anchor="middle" font-size="22" fill="{ink}">{b}</text>',
                      f'<text x="{x+width/2}" y="192" text-anchor="middle" font-size="12" fill="{color}">{label}</text>',
                      f'<text x="{x+width/2}" y="223" text-anchor="middle" font-size="12" fill="{muted}">parts</text>',
                      f'<text x="{x+width/2}" y="250" text-anchor="middle" font-size="20" fill="{ink}">{b+(8*b+16)//17}</text>'])
    parts.extend([f'<text x="32" y="323" font-size="17" fill="{ink}">Blue: nine explicit even-side weaves. Copper: seven saved odd-base edge certificates.</text>',
                  f'<text x="32" y="355" font-size="17" fill="{ink}">Green: the 17-leaf offset block. Each color reaches the parity/capacity lower bound.</text>',
                  f'<text x="32" y="395" font-size="13" fill="{muted}">Finite theorem for h=17 · Uniform odd-hub construction still open in this playground · Marlow</text>'])
    path.write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1450 420" width="1450" height="420" role="img" aria-label="Seventeen base residues for K seventeen t, classified by even weave, offset block, and explicit walks" font-family="Georgia,serif">' + ''.join(parts) + '</svg>\n')


def main():
    for base in range(16, 33):
        for blocks in range(12):
            certificate(base, blocks)
    draw(HERE / 'art/seventeen_hub_residue_ladder.svg')
    print('Verified all 17 base residues and lifts through 11 added blocks.')
    print('Even bases generated by explicit weave; wrote residue ladder.')


if __name__ == '__main__':
    main()
